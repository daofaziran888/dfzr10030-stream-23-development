"""恢复检查点子系统的领域异常与状态常量。

所有状态字符串集中在此，避免各模块各写一份导致状态机不一致。
"""
from __future__ import annotations


class RecoveryError(Exception):
    """领域规则被违反时抛出；路由层统一翻译成可读的失败响应。"""


# 恢复检查点（恢复检查点清单）的状态机
CHECKPOINT_STATUSES = (
    "已登记",      # 旧检查点与结构演进各自登记，尚未判定可恢复性
    "可恢复",      # 存在一条能读到其状态格式的演进路径
    "不可恢复",    # 找不到任何仍可用的状态格式
    "排队中",      # 已进入恢复队列，等待结构切换窗口
    "转换中",      # 所属转换批次正在做状态格式转换
    "已转换",      # 批次整体提交，检查点已按新格式落盘
    "恢复中",      # 正在把批次状态装回流水线
    "已恢复",      # 装载完成，已记录实际装载格式以便追查
    "已回滚",      # 所属批次整体回滚，检查点保持源格式完整版本
)

# 状态格式转换批次的状态机
BATCH_STATUSES = (
    "已创建",      # 批次已登记，依赖校验通过前不允许启动
    "依赖已校验",  # 流水线上下游依赖与字段映射均已通过
    "转换中",      # 已写暂存区，尚未整体提交（中途崩溃只会停在这）
    "已提交",      # 同批数据整体切换为目标格式，对外可读
    "已回滚",      # 整体退回源格式完整版本，暂存内容不可读
    "已失败",      # 校验或转换失败被拒绝，未产生半转换数据
)

# 恢复队列条目的状态机
QUEUE_STATUSES = ("排队中", "处理中", "已完成", "已取消")

# 结构演进记录的状态机
EVOLUTION_STATUSES = ("草稿", "已登记", "已生效", "已回滚")

